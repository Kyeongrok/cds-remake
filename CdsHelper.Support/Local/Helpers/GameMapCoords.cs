    /// <summary>
    /// 도시 중심을 펼친 칸 좌표(x 0~2500, y 0~1250)로. 소수를 그대로 두어 원본값의
    /// 1/16 칸 해상도를 잃지 않는다. 없는 ID 면 false.
    /// </summary>
    public static bool TryCityCell(int cityId, out double cellX, out double cellY)
    {
        cellX = cellY = 0;
        if (cityId < 0 || cityId >= CityCount) return false;
        cellX = CityLonRaw[cityId] * (double)WorldMapRenderer.UnfoldedW / LonRawMax;
        cellY = CityLatRaw[cityId] * (double)WorldMapRenderer.CellH / LatRawMax;
        return true;
    }

    /// <summary>
    /// 발견물 범위를 펼친 칸 좌표로. <paramref name="index"/> 는 게임 발견물 번호(0~273).
    /// 좌표가 없는 발견물이면 false.
    /// </summary>
    public static bool TryDiscoveryCells(int index, out double x1, out double y1, out double x2, out double y2)
    {
        x1 = y1 = x2 = y2 = 0;
        if (index < 0 || index >= DiscoveryCount) return false;
        int o = index * 4;
        if (DiscoveryBox[o] == DiscoveryNone) return false;
        x1 = DiscoveryBox[o];
        y1 = DiscoveryBox[o + 1];
        x2 = DiscoveryBox[o + 2];
        y2 = DiscoveryBox[o + 3];
        return true;
    }

    /// <summary>cds-helper DB 의 발견물 Id 를 게임 발견물 번호로. 표 밖이면 -1.</summary>
    public static int IndexFromDbId(int dbId)
    {
        int i = dbId - DiscoveryIdOffset;
        return i >= 0 && i < DiscoveryCount ? i : -1;
    }

    /// <summary>게임 발견물 번호를 cds-helper DB 의 Id 로.</summary>
    public static int DbIdFromIndex(int index) => index + DiscoveryIdOffset;

    /// <summary>지도에 찍을 좌표가 있는 발견물 수(147개).</summary>
    public static int DiscoveryWithCoords
    {
        get
        {
            int n = 0;
            for (int i = 0; i < DiscoveryCount; i++)
                if (DiscoveryBox[i * 4] != DiscoveryNone) n++;
            return n;
        }
    }
