    /// <summary>그 여자가 제 취향을 말한다. 성격이 표 밖이면 null.</summary>
    public static string? OwnTasteOf(int personality) =>
        personality >= 0 && personality < OwnTastes.Length ? OwnTastes[personality] : null;

    /// <summary>그 여자의 취향 이야기 한 마디. 성격이 표 밖이면 null(원본은 말이 없다).</summary>
    public static string? TasteOf(string name, int personality, Random random)
    {
        if (personality < 0 || personality >= Tastes.Length) return null;
        int pick = random.Next(2);
        string[] args = personality == 6
            ? [name, NameToken.Of(name, 2), name, NameToken.Of(name, 1)]
            : [name, NameToken.Of(name, personality is 1 or 3 && pick == 1 ? 0 : 1)];
        return Printf(Tastes[personality][pick], args);
    }

    /// <summary>C 의 <c>%s</c> 만 차례로 채운다.</summary>
    private static string Printf(string format, string[] args)
    {
        var made = new StringBuilder();
        int next = 0;
        for (int i = 0; i < format.Length; i++)
        {
            if (format[i] == '%' && i + 1 < format.Length && format[i + 1] == 's')
            {
                made.Append(next < args.Length ? args[next++] : "");
                i++;
            }
            else made.Append(format[i]);
        }
        return made.ToString();
    }

    /// <summary>
    /// 이야깃거리를 고른다(<c>0x004A43F0</c>). 여자 이름·성격이 있으면 그 마을 여자 갈래도 굴린다.
    /// </summary>
    /// <param name="culture">
    /// 손님이 온 도시의 문화권. 원본은 반쯤 손님을 <b>그 나라 수도</b> 사람으로 바꿔 앉힌다(<c>0x004A14F0</c>) —
    /// 신대륙 식민 도시에서도 유럽 이야기가 나오는 까닭이다.
    /// </param>
    /// <param name="homeCulture">손님이 앉은 이 도시의 문화권. 뭍 이야기 앞 넷(신대륙 남쪽)이 여기서 갈린다.</param>
    /// <param name="cityRumors">그 도시의 살아 있는 소문.</param>
    /// <param name="woman">그 마을에 선 여자(아내 말고). 없으면 null.</param>
    /// <param name="cultureRumor">문화권 소문을 내는 길.</param>
    public static string? Pick(int culture, int homeCulture, IReadOnlyList<string> cityRumors, (string Name, int Personality)? woman,
                               Func<string> cultureRumor, Random random)
    {
        if (cityRumors.Count > 0 && random.Next(2) != 0)
            return cityRumors[random.Next(cityRumors.Count)];

        if (culture is >= 0 and <= 2 && random.Next(2) != 0)
        {
            switch (random.Next(woman != null ? 3 : 2))
            {
                case 0:
                    return SeaLegends[random.Next(SeaLegends.Length)];
                case 1:
                    // 앞 넷은 이 도시가 신대륙(문화권 10)이고 손님이 본국 수도 사람일 때만 나온다(0x004A4550).
                    return homeCulture == 10 ? LandLore[random.Next(LandLore.Length)]
                                         : LandLore[random.Next(LandLore.Length - 4) + 4];
                default:
                    return TasteOf(woman!.Value.Name, woman.Value.Personality, random);
            }
        }
        return cultureRumor();
    }
