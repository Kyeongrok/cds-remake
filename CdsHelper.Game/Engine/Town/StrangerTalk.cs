///   그 도시에 살아 있는 소문이 있고 rand(2)        갈래 9  도시 소문            0x4A3080
///   아니면 유럽(문화권 0~2)이고 rand(2)             rand(2) 또는 rand(3)
///                                                   10 바다 전설 26줄        0x4A40C0
///                                                   11 뭍 이야기 33줄        0x4A4210  (문화권 10 이 아니면 앞 넷 빼고)
///                                                   12 그 마을 여자 취향      0x4A3130  (그 마을에 여자가 있을 때만 rand(3))
///   그 밖                                           문화권 소문              0x4A3740
/// </code>
/// 말은 모두 <c>0x004690A0</c> 창으로 나가며, 자리 말(나라 말)을 <b>제독 수준</b>으로 뭉갠다(<see cref="Garble"/>).
/// 부관(자리 0·3)이 제독보다 <b>잘하면</b> 뭉개진 말 뒤에 부관이 「[…]라고 하는 것 같네요.」로 옮긴다.
