/// </summary>
/// <remarks>
/// 게임의 소문 표(<c>0x004A37C0</c>)를 그대로 옮겼다. 그 함수는 아홉 벌짜리 문줄표를
/// 통째로 세우고 <c>표[갈래][줄]</c> 로 집는다.
/// <code>
///   0x004A3740  갈래가 -1 이면 도시에서 캔다 — 0x429970(도시) 의 +0x58 이 문화권
///   0x004A3000  문화권(0~10) -> 소문 갈래(0~8)   점프표 0x004A3048
///   0x004A36D0  갈래 안에서 줄을 고른다
///   0x004A37C0  표[갈래][줄] -> 문줄
/// </code>
/// 문화권 열하나가 갈래 아홉으로 접힌다 — <b>앞의 셋(북유럽·이베리아·지중해)이 한 벌</b>을
/// 함께 쓴다. 손님 그림 구간이 접히는 것과 같은 꼴이다(<see cref="Local.Helpers.TavernGuests"/>).
/// </remarks>
public static class TavernRumors
