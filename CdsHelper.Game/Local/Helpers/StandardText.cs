        (new Regex("(?<![가-힣])투라(?=[를에의은는이가과와]|라는|$)", RegexOptions.Compiled), "툴라"),
        // 도시 「시높」 · 「시빌」 — 짧아 앞뒤를 본다. 「시빌」은 나라 「이빌·시빌」(시비르 칸국) 속의 것은 그대로 둔다.
        (new Regex("(?<![가-힣])시높(?![가-힣])|(?<![가-힣])시높(?=항)", RegexOptions.Compiled), "시노프"),
