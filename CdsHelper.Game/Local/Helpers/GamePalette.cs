namespace CdsHelper.Game.Local.Helpers;

/// <summary>
/// 게임이 낮은 색인(0~73)에 공용으로 깔아 두는 색표 256색. 도시 그림·아이템 그림·인물
/// 초상화가 함께 쓴다. 한 색이 3바이트 R,G,B 순이다.
/// </summary>
/// <remarks>
/// cds95-mod 의 plugins-src/CharacterUtilKR/src/game_palette.h 를 그대로 옮겼다.
/// 그쪽 설명대로 이 구간의 값은 파일 어디에도 통짜로 들어 있지 않아 그림에서 되짚은 것이다 —
/// 그림들이 두 색을 바둑판으로 섞어 중간색을 내므로, 낮은 색인 픽셀에 맞닿은 높은 색인
/// 픽셀의 색(이쪽은 그림마다 팔레트에 정확히 적혀 있다)을 모아 중앙값을 취하면 나온다.
///
/// 74 위쪽은 그림마다 제 팔레트가 얹히는 자리라 여기서는 쓰이지 않는다. 원본도 채움값
/// (12,7,6)으로만 채워 두었으므로 여기서도 표를 늘어놓지 않고 그 값으로 메운다.
/// </remarks>
public static class GamePalette
{
    /// <summary>그림마다 제 팔레트가 얹히기 시작하는 색인. 그 아래만 이 표를 쓴다.</summary>
    public const int OwnPaletteBase = 74;

    // 0~73 만 진짜 값이다. 0~9 는 게임이 딴 데 쓰는 자리라 회색 하나로 채워져 있다.
    // (Rgb 보다 먼저 적어야 한다 — 정적 필드는 적힌 차례대로 채워진다.)
    private static readonly byte[] Low =
    [
        186,186,186, 186,186,186, 186,186,186, 186,186,186, 186,186,186, 186,186,186, 186,186,186, 186,186,186,
        186,186,186, 186,186,186, 244,232,224, 144,140,140,  64, 60, 52,  96,100,100,  60, 44, 40,  96, 60, 56,
         72, 48, 40,  52, 28, 20,  92, 56, 44, 116,104, 92,  88, 68, 52, 128,120,108, 180,172,156, 140,120, 92,
        132,116, 84,  80, 56, 36, 196,180,148, 156,132, 96, 112, 92, 72, 160,148,136, 224,192,160, 104, 88, 68,
        236,200,176,  88, 88, 76, 144,136,116, 236,204,172, 188,168,128, 168,144,108,  88, 72, 56, 132,108, 72,
        244,216,176, 248,224,196, 224,212,192, 212,200,176,  44, 52, 72,  32, 72,100,  48, 64,100,  52, 76,100,
         72, 88,108,  80, 96,112,  24, 36, 48,  32, 72,100,  56, 72,100,  76,100,128,  84,100,128,  84,100,128,
         96,116,136, 104,124,140, 108, 44, 12, 120, 56, 36, 148, 64, 52, 156, 76, 64, 160, 96, 84, 172,104, 96,
        172,124,100, 184,128,116,  48, 72, 32,   0,100,  4,  56, 96, 56,  80,136, 76, 106,132,104,  84,130, 80,
        120,148,118,  24, 20, 12,
    ];

    /// <summary>256색 x 3바이트(R,G,B).</summary>
    public static readonly byte[] Rgb = Build();

    private static byte[] Build()
    {
        var rgb = new byte[256 * 3];
        Low.CopyTo(rgb, 0);
        for (int i = Low.Length; i + 2 < rgb.Length; i += 3)
        {
            rgb[i] = 12;
            rgb[i + 1] = 7;
            rgb[i + 2] = 6;
        }
        return rgb;
    }
}
